-- Explicit deployment migration. Application requests never execute DDL.
CREATE SCHEMA IF NOT EXISTS fhdod;
REVOKE ALL ON SCHEMA fhdod FROM PUBLIC;
CREATE TABLE IF NOT EXISTS fhdod.schema_version (version integer PRIMARY KEY);
CREATE TABLE IF NOT EXISTS fhdod.questions (
  id text PRIMARY KEY,
  sector_id text NOT NULL,
  current_version integer NOT NULL CHECK (current_version > 0),
  position bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE IF NOT EXISTS fhdod.question_versions (
  question_id text NOT NULL REFERENCES fhdod.questions(id),
  version integer NOT NULL CHECK (version > 0),
  text text NOT NULL,
  created_at text NOT NULL,
  PRIMARY KEY (question_id, version)
);
CREATE TABLE IF NOT EXISTS fhdod.surveys (
  id text PRIMARY KEY,
  created_at text NOT NULL,
  payload_hash text NOT NULL,
  nps integer CHECK (nps IS NULL OR nps BETWEEN 0 AND 10),
  comment text NOT NULL,
  shift text NOT NULL CHECK (shift IN ('par','impar','nao-informado')),
  doctor text NOT NULL
);
CREATE TABLE IF NOT EXISTS fhdod.survey_sectors (
  survey_id text NOT NULL REFERENCES fhdod.surveys(id) ON DELETE CASCADE,
  sector_id text NOT NULL,
  PRIMARY KEY (survey_id, sector_id)
);
CREATE TABLE IF NOT EXISTS fhdod.answers (
  survey_id text NOT NULL REFERENCES fhdod.surveys(id) ON DELETE CASCADE,
  question_id text NOT NULL,
  question_version integer NOT NULL,
  sector_id text NOT NULL,
  value integer NOT NULL CHECK (value BETWEEN 1 AND 5),
  PRIMARY KEY (survey_id, question_id),
  FOREIGN KEY (question_id, question_version) REFERENCES fhdod.question_versions(question_id, version)
);
CREATE TABLE IF NOT EXISTS fhdod.users (
  id text PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL,
  role text NOT NULL CHECK (role IN ('manager','sector-admin','management','ombudsman','viewer')),
  sector_id text,
  password_salt text NOT NULL,
  password_hash text NOT NULL,
  created_at text NOT NULL,
  must_change_password integer NOT NULL DEFAULT 0 CHECK (must_change_password IN (0,1)),
  CHECK ((role IN ('manager','management','ombudsman','viewer') AND sector_id IS NULL) OR (role = 'sector-admin' AND sector_id IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email ON fhdod.users (lower(email));
CREATE TABLE IF NOT EXISTS fhdod.sessions (
  token_hash text PRIMARY KEY,
  user_id text NOT NULL REFERENCES fhdod.users(id) ON DELETE CASCADE,
  csrf_token text NOT NULL,
  expires_at bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS fhdod.question_audit (
  id text PRIMARY KEY,
  question_id text NOT NULL REFERENCES fhdod.questions(id),
  user_id text NOT NULL REFERENCES fhdod.users(id),
  previous_version integer NOT NULL,
  next_version integer NOT NULL,
  created_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS fhdod.account_audit (
  id text PRIMARY KEY,
  user_id text NOT NULL REFERENCES fhdod.users(id),
  actor_id text REFERENCES fhdod.users(id),
  event text NOT NULL CHECK (event IN ('user_created','password_changed')),
  created_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS fhdod.survey_settings_versions (
  version integer PRIMARY KEY CHECK (version > 0),
  settings_json text NOT NULL,
  created_at text NOT NULL,
  user_id text REFERENCES fhdod.users(id)
);
CREATE TABLE IF NOT EXISTS fhdod.contact_requests (
  id text PRIMARY KEY,
  survey_id text NOT NULL UNIQUE REFERENCES fhdod.surveys(id) ON DELETE CASCADE,
  created_at text NOT NULL,
  name text NOT NULL,
  phone text NOT NULL,
  email text NOT NULL,
  message text NOT NULL,
  settings_version integer NOT NULL REFERENCES fhdod.survey_settings_versions(version),
  consent_text text NOT NULL,
  status text NOT NULL CHECK (status IN ('novo','em-analise','concluido'))
);
CREATE TABLE IF NOT EXISTS fhdod.contact_status_audit (
  id text PRIMARY KEY,
  contact_id text NOT NULL REFERENCES fhdod.contact_requests(id),
  user_id text NOT NULL REFERENCES fhdod.users(id),
  previous_status text NOT NULL,
  next_status text NOT NULL,
  created_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS fhdod.rate_limits (
  key_hash text PRIMARY KEY,
  count integer NOT NULL,
  until_ms bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS surveys_created_at ON fhdod.surveys(created_at);
CREATE INDEX IF NOT EXISTS sector_surveys ON fhdod.survey_sectors(sector_id,survey_id);
CREATE INDEX IF NOT EXISTS sessions_expiration ON fhdod.sessions(expires_at);
CREATE INDEX IF NOT EXISTS contacts_created_at ON fhdod.contact_requests(created_at);
CREATE INDEX IF NOT EXISTS contacts_status ON fhdod.contact_requests(status);
CREATE INDEX IF NOT EXISTS rate_limit_expiration ON fhdod.rate_limits(until_ms);
DO $security$
DECLARE t record; r text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'fhdod' LOOP
    EXECUTE format('ALTER TABLE fhdod.%I ENABLE ROW LEVEL SECURITY', t.tablename);
    EXECUTE format('REVOKE ALL ON TABLE fhdod.%I FROM PUBLIC', t.tablename);
  END LOOP;
  FOR r IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon','authenticated') LOOP
    EXECUTE format('REVOKE ALL ON SCHEMA fhdod FROM %I', r);
    EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA fhdod FROM %I', r);
    EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA fhdod FROM %I', r);
  END LOOP;
END $security$;
